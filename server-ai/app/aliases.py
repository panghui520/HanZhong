"""领域别名表：把口语与简称归一成语料里的规范写法。

为什么需要它：字符 n-gram 检索靠字面重合，而中文口语和书面语常常不同形。
最典型的一例——用户问"怎么坐**高铁**去汉中"，而知识库里写的是"西成**高速铁路**"，
"高铁"这个 bigram 在语料里根本不存在，检索直接落空。

这不是字符 n-gram 独有的问题：换成 jieba 分词，"高铁"是一个词、"高速铁路"是
"高速"+"铁路"，一样对不上；换成稠密向量模型才能靠语义泛化解决，但那要 GB 级依赖
且首次使用要联网下载模型，不适合单机演示。

所以这里维护一张**小而明确的领域别名表**，在文本归一化阶段双向统一：
文档与查询都过一遍，写"高铁"的文档和问"高铁"的人会落到同一个特征上。
表的规模刻意保持很小——只放确实会造成漏检的高频说法，不做同义词大杂烩，
因为每加一条都是一次人工判断，加多了没人维护得起。
"""

from __future__ import annotations

import hashlib

# 口语/简称 -> 规范写法。键与值都必须是语料里可能出现的说法，
# 归一化后两边都变成「值」，所以「值」要选更书面、更可能在文档中出现的那个。
ALIASES: dict[str, str] = {
    # 交通
    "高铁": "高速铁路",
    "动车": "高速铁路",
    "火车": "铁路",
    "飞机": "机场",
    "航班": "机场",
    "航线": "机场",
    "怎么去": "交通",
    "怎么走": "交通",
    "咋去": "交通",
    "咋走": "交通",
    # 气候
    "天气": "气候",
    "气温": "气候",
    "什么时候去": "最佳季节",
    "几月去": "最佳季节",
    # 季节：语料用书面语（冬季/夏季），用户口语说（冬天/夏天）。
    # 这一组是实测补上的——问"汉中冬天冷不冷"原本会落到无关文档，
    # 因为语料里只有"冬季"，"冬天"这个 bigram 根本不存在。
    "冬天": "冬季",
    "夏天": "夏季",
    "春天": "春季",
    "秋天": "秋季",
    "开春": "春季",
    # 饮食
    "面皮": "热面皮",
    "小吃": "早餐",
    # 生态
    "熊猫": "大熊猫",
    "鸟": "朱鹮",
    # 物产
    "特产": "物产",
    "伴手礼": "物产",
    "土特产": "物产",
    # 文化：全称在语料里没有，简称"非遗"有
    "非物质文化遗产": "非遗",
}

# 长键优先，避免"高速铁路"里的"铁路"先被替换
_ORDERED: list[tuple[str, str]] = sorted(ALIASES.items(), key=lambda kv: -len(kv[0]))


def fingerprint() -> str:
    """别名表的指纹。

    别名表参与分词，改一条就等于换了特征空间——已入库的向量与 IDF 全部作废。
    把它算进向量化实现的签名（见 embed.NgramEmbedder.signature），
    改别名会自动落到另一个 Chroma 集合上，不会拿旧向量当新结果用。
    """
    digest = hashlib.blake2b(digest_size=8)
    for src, dst in sorted(ALIASES.items()):
        digest.update(f"{src}\x00{dst}\x01".encode("utf-8"))
    return digest.hexdigest()


def expand(text: str) -> str:
    """按别名表归一化文本。

    替换用带序号的占位符隔开，最后统一还原。这样两件事都成立：
    - 已经替换出来的规范写法不会被后面的短键二次替换
      （否则 面皮 -> 热面皮 之后，"热面皮"里的"面皮"会被再换一次）
    - 不做级联替换，一条别名只生效一次，结果可预期
    """
    if not text:
        return text

    marks: dict[str, str] = {}
    for index, (src, dst) in enumerate(_ORDERED):
        if src in text:
            token = f"\x00{index}\x00"
            text = text.replace(src, token)
            marks[token] = dst

    for token, dst in marks.items():
        text = text.replace(token, dst)
    return text
